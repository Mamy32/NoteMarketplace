import { creatorById } from '../data';
import type { Block, Note } from '../types';

/**
 * Demo download: builds a small, real PDF in the browser from the note's sample pages.
 * (The prototype does not ship the creators' full PDFs.)
 */

const MAP: Record<string, string> = {
  '—': '-', '–': '-', '−': '-', '…': '...', '“': '"', '”': '"', '‘': "'", '’': "'", '·': '|', '•': '*',
  '→': '->', '⇢': '..>', '←': '<-', '≥': '>=', '≤': '<=', '≈': '~', '≡': '==', '≠': '!=', '×': 'x',
  '²': '^2', '³': '^3', 'ⁿ': '^n', 'ᵀ': '^T', '⁻': '^-', '¹': '1', 'ᵈ': '^d', 'ᵢ': '_i', 'ₙ': '_n',
  '∑': 'Sum', 'Σ': 'Sum', 'π': 'pi', 'λ': 'lambda', 'μ': 'mu', 'σ': 'sigma', 'α': 'alpha', 'ŷ': 'y-hat',
  '∪': ' U ', '∩': ' n ', '∧': ' AND ', '∨': ' OR ', '¬': 'NOT ', '⌊': 'floor(', '⌋': ')', '∂': 'd', '·.': '.',
  '✓': 'ok', '₂': '2', '◇': '<>', '◆': '<#>', '▷': '>', '«': '<<', '»': '>>', 'é': 'e',
};

function ascii(s: string): string {
  let out = '';
  for (const ch of s) {
    const c = ch.codePointAt(0)!;
    if (c >= 32 && c < 127) out += ch;
    else if (MAP[ch] !== undefined) out += MAP[ch];
    else if (c === 9) out += '    ';
    else if (c === 10) out += '\n';
    else out += '?';
  }
  return out;
}

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');

type Font = 'F1' | 'F2' | 'F3';
interface Line { font: Font; size: number; text: string; gap?: number; indent?: number }

function wrap(text: string, max: number): string[] {
  const out: string[] = [];
  for (const raw of text.split('\n')) {
    let line = raw;
    if (line.length <= max) { out.push(line); continue; }
    const words = line.split(' ');
    line = '';
    for (const w of words) {
      if ((line + ' ' + w).trim().length > max) { if (line) out.push(line); line = w; } else line = (line + ' ' + w).trim();
    }
    if (line) out.push(line);
  }
  return out;
}

function blockLines(b: Block): Line[] {
  const L: Line[] = [];
  const text = (t: string, font: Font = 'F1', size = 10.5, gap = 4, indent = 0) =>
    wrap(ascii(t), Math.floor((495 - indent) / (size * (font === 'F3' ? 0.6 : 0.5)))).forEach((t2, i) => L.push({ font, size, text: t2, gap: i === 0 ? gap : 0, indent }));
  switch (b.t) {
    case 'h': text(b.text, 'F2', 13, 12); break;
    case 'p': text(b.text, 'F1', 10.5, 6); break;
    case 'ul': b.items.forEach((it, i) => text('- ' + it, 'F1', 10.5, i === 0 ? 6 : 2, 8)); break;
    case 'code': text(b.code, 'F3', 8.5, 6, 6); break;
    case 'math': b.lines.forEach((l, i) => text(l, 'F3', 9.5, i === 0 ? 6 : 1, 6)); break;
    case 'table': {
      const rows = [b.head, ...b.rows].map((r) => r.map(ascii));
      const w = b.head.map((_, i) => Math.max(...rows.map((r) => (r[i] ?? '').length)));
      rows.forEach((r, ri) => {
        const line = r.map((c, i) => c.padEnd(w[i])).join(' | ');
        text(line, 'F3', 8.5, ri === 0 ? 6 : 1, 4);
        if (ri === 0) text('-'.repeat(Math.min(line.length, 100)), 'F3', 8.5, 0, 4);
      });
      break;
    }
    case 'flow': text(b.steps.map((s) => `[${s}]`).join(b.vertical ? '\n  v\n' : ' -> ') + (b.caption ? `\n(${b.caption})` : ''), 'F3', 8.5, 6, 6); break;
    case 'tree': text(b.levels.map((lv) => lv.join('    ')).join('\n') + (b.caption ? `\n(${b.caption})` : ''), 'F3', 9, 6, 6); break;
    case 'callout': text(b.title.toUpperCase(), 'F2', 9.5, 8, 6); text(b.text, 'F1', 10.5, 0, 6); break;
  }
  return L;
}

export function buildNotePdf(note: Note): Blob {
  const creator = creatorById(note.creatorId);
  const pages: Line[][] = [];
  let cur: Line[] = [];
  let y = 0;
  const TOP = 790;
  const BOTTOM = 70;
  const newPage = () => { cur = []; pages.push(cur); y = TOP; };
  const push = (l: Line) => {
    const h = l.size * 1.3 + (l.gap ?? 0);
    if (y - h < BOTTOM || pages.length === 0) newPage();
    y -= h;
    cur.push({ ...l, gap: y }); // gap field reused as absolute y
  };

  newPage();
  push({ font: 'F3', size: 9, text: ascii(`${note.courseCode} | ${note.courseName}`) });
  wrap(ascii(note.title), 40).forEach((t, i) => push({ font: 'F2', size: 22, text: t, gap: i === 0 ? 18 : 0 }));
  push({ font: 'F1', size: 11, text: ascii(`by ${creator?.name ?? 'Student'} | ${note.university}`), gap: 12 });
  push({ font: 'F1', size: 11, text: ascii(`Semester ${note.semester} | ${note.term} | ${note.pages} pages in the full note`), gap: 2 });
  wrap(ascii(note.description), 82).forEach((t, i) => push({ font: 'F1', size: 10.5, text: t, gap: i === 0 ? 18 : 0 }));
  push({ font: 'F2', size: 11, text: 'Topics covered', gap: 16 });
  note.topics.forEach((t) => push({ font: 'F1', size: 10.5, text: '- ' + ascii(t), gap: 2 }));
  push({ font: 'F2', size: 9.5, text: 'DEMO FILE', gap: 28 });
  wrap('Generated by BombaNotes. This prototype bundles only the sample pages of each note, so this PDF contains those pages, not the creator\'s full document. All names and content are fictional demo data.', 90).forEach((t) => push({ font: 'F1', size: 9.5, text: t }));

  note.preview.forEach((p, i) => {
    newPage();
    push({ font: 'F3', size: 8.5, text: ascii(`${note.courseCode} | page ${i + 1}`) });
    push({ font: 'F2', size: 17, text: ascii(p.title), gap: 10 });
    p.blocks.forEach((b) => blockLines(b).forEach(push));
  });

  // ---- serialise ----
  const objs: string[] = [];
  const add = (body: string) => { objs.push(body); return objs.length; };
  add('<< /Type /Catalog /Pages 2 0 R >>');
  add('PAGES_PLACEHOLDER');
  add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');
  add('<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>');
  const pageIds: number[] = [];
  pages.forEach((lines, pi) => {
    const parts = lines.map((l) => `BT /${l.font} ${l.size} Tf ${56 + (l.indent ?? 0)} ${l.gap!.toFixed(1)} Td (${esc(l.text)}) Tj ET`);
    parts.push(`BT /F3 8 Tf 56 36 Td (${esc(`BombaNotes demo | ${ascii(note.courseCode)} | ${pi + 1}/${pages.length}`)}) Tj ET`);
    const stream = parts.join('\n');
    const cid = add(`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`);
    pageIds.push(add(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R /F2 4 0 R /F3 5 0 R >> >> /Contents ${cid} 0 R >>`));
  });
  objs[1] = `<< /Type /Pages /Count ${pageIds.length} /Kids [${pageIds.map((i) => `${i} 0 R`).join(' ')}] >>`;

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objs.forEach((o, i) => { offsets.push(pdf.length); pdf += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = pdf.length;
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offsets.map((o) => String(o).padStart(10, '0') + ' 00000 n \n').join('');
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([pdf], { type: 'application/pdf' });
}

export function noteFileName(note: Note): string {
  const slug = note.title.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
  return `${note.courseCode.toLowerCase()}-${slug}.pdf`;
}

export function downloadNote(note: Note): string {
  const blob = buildNotePdf(note);
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = noteFileName(note);
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 2000);
  return a.download;
}
